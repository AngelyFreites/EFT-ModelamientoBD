-- =========================================================
-- INFORME 1: ASOCIACIONES DE FUTBOL PROFESIONAL
-- Tipo profesional (P)
-- Creadas despues del año 2000
-- Orden descendente por fecha de creacion
-- =========================================================

SELECT id_asociacion AS "Código",
       nombre_asociacion AS "Asociación",
       fecha_creacion AS "Fecha de creación",
       tipo_asociacion AS "Tipo"
FROM ASOCIACION
WHERE tipo_asociacion = 'P'
  AND fecha_creacion > DATE '2000-12-31'
ORDER BY fecha_creacion DESC;


-- =========================================================
-- INFORME 2: PATRIMONIO DE CLUBES DE FUTBOL
-- Nombre contiene la letra a
-- Patrimonio superior a $200.000.000
-- Tipo profesional
-- Conversion a dolares a $955
-- Orden descendente por codigo
-- =========================================================

SELECT id_club AS "Código",
       nombre_club AS "Club",
       patrimonio AS "Patrimonio en pesos",
       ROUND(patrimonio / 955, 2) AS "Patrimonio en dólares"
FROM CLUB_FUTBOL
WHERE LOWER(nombre_club) LIKE '%a%'
  AND patrimonio > 200000000
  AND tipo_club = 'Profesional'
ORDER BY id_club DESC;
