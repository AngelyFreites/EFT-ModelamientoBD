    ADD CONSTRAINT REGION_PK
    PRIMARY KEY (id_region);


-- =========================================================
-- NACIONALIDAD
-- PK generada mediante IDENTITY:
-- inicia en 210 e incrementa de 2 en 2
-- =========================================================

CREATE TABLE NACIONALIDAD
(
    id_nacionalidad NUMBER(3)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 210 INCREMENT BY 2)
        NOT NULL,

    descripcion VARCHAR2(60) NOT NULL
);

ALTER TABLE NACIONALIDAD
    ADD CONSTRAINT NACIONALIDAD_PK
    PRIMARY KEY (id_nacionalidad);


-- =========================================================
-- ASOCIACION
-- =========================================================

CREATE TABLE ASOCIACION
(
    id_asociacion     NUMBER(6) NOT NULL,
    nombre_asociacion VARCHAR2(60) NOT NULL,
    fecha_creacion    DATE NOT NULL,
    tipo_asociacion   CHAR(1 CHAR) NOT NULL
);

ALTER TABLE ASOCIACION
    ADD CONSTRAINT ASOCIACION_PK
    PRIMARY KEY (id_asociacion);

ALTER TABLE ASOCIACION
    ADD CONSTRAINT ASOCIACION_FECHA_CK
    CHECK (fecha_creacion >= DATE '1980-12-31');

ALTER TABLE ASOCIACION
    ADD CONSTRAINT ASOCIACION_TIPO_CK
    CHECK (tipo_asociacion IN ('P', 'A'));


